import httpx
import logging
from typing import List, Dict

logger = logging.getLogger("negotiator")

class Negotiator:
    """
    Initializes the agent with its country name, starting positions, and the Ollama endpoint.
    Params:
      - country (str): The persona of the agent (e.g., 'usa')
      - positions (dict): The specific priorities loaded from the JSON data file
      - ollama_url (str): The base URL of the Ollama service, derived from environment variables
    """
    def __init__(self, country: str, positions: dict, ollama_url: str):
        self.country = country
        self.positions = positions
        self.ollama_url = ollama_url.rstrip("/") if ollama_url else "http://ollama:11434"
        self.model = "llama3"

    async def generate_response(self, prompt: str) -> str:
        """
        Asynchronously sends a crafted prompt to the Ollama API.
        Returns: The text string response generated by the LLM.
        """
        endpoint = f"{self.ollama_url}/api/generate"
        payload = {
            "model": self.model,
            "prompt": prompt,
            "stream": False,
            "options": {
                "temperature": 0.3
            }
        }
        
        try:
            async with httpx.AsyncClient(timeout=10.0) as client:
                res = await client.post(endpoint, json=payload)
                if res.status_code == 200:
                    data = res.json()
                    response_text = data.get("response", "").strip()
                    if response_text:
                        return self._clean_response(response_text)
        except Exception as e:
            logger.warning(f"Ollama call failed or timed out ({e}). Using fallback prompt response.")

        # Fallback response referencing initial priorities directly
        return self._generate_fallback_response()

    async def make_proposal(self, issue: str, history: List[Dict]) -> str:
        """
        Constructs the prompt combining persona, priorities, and negotiation history.
        Returns: A new proposal generated by the LLM via generate_response.
        """
        country_name = self.country.upper()
        priorities = self.positions.get("priorities", [])
        priorities_str = "; ".join(priorities) if priorities else "standard trade terms"

        history_context = ""
        if history:
            history_lines = []
            for item in history:
                r_num = item.get("round", "")
                usa_p = item.get("usa_proposal", "")
                china_r = item.get("china_response", "")
                history_lines.append(f"Round {r_num}: USA proposed: '{usa_p}' | China responded: '{china_r}'")
            history_context = "Previous History:\n" + "\n".join(history_lines) + "\n"

        prompt = (
            f"You are a diplomat representing {country_name} in trade negotiations on the issue of '{issue}'.\n"
            f"Your country's core priorities are: {priorities_str}.\n"
            f"{history_context}"
            f"Respond with a single concise sentence (1-2 sentences max) detailing your proposal or response. "
            f"You must explicitly address your priorities ({priorities_str}). "
            f"Do not include intro text or markdown formatting."
        )

        return await self.generate_response(prompt)

    def _clean_response(self, text: str) -> str:
        """Strips unwanted preambles or quotes from LLM output."""
        cleaned = text.strip()
        if cleaned.startswith('"') and cleaned.endswith('"'):
            cleaned = cleaned[1:-1].strip()
        lines = [line.strip() for line in cleaned.splitlines() if line.strip()]
        if lines:
            # Pick first substantive line if preamble exists
            for line in lines:
                if not line.lower().startswith("here is") and not line.lower().startswith("sure"):
                    return line
            return lines[0]
        return cleaned

    def _generate_fallback_response(self) -> str:
        """Generates a structured proposal using defined priorities if LLM service is offline."""
        priorities = self.positions.get("priorities", [])
        priorities_str = " and ".join(priorities) if priorities else "balanced trade terms"
        if self.country.lower() == "usa":
            return f"The USA proposes a trade agreement to {priorities_str}."
        elif self.country.lower() == "china":
            return f"China agrees to negotiate provided we {priorities_str}."
        return f"{self.country.upper()} proposes to address {priorities_str}."
