import httpx
import logging
import os
from typing import List, Dict, Optional

logger = logging.getLogger("negotiator")

class Negotiator:
    # Initializes the agent with its country name, starting positions, and the Ollama endpoint.
    # Params:
    #   - country (str): The persona of the agent (e.g., 'usa')
    #   - positions (dict): The specific priorities loaded from the JSON data file
    #   - ollama_url (str): The base URL of the Ollama service, derived from environment variables
    def __init__(self, country: str, positions: dict, ollama_url: str):
        self.country = country
        self.positions = positions
        self.ollama_url = ollama_url.rstrip("/") if ollama_url else "http://ollama:11434"
        self.model = os.getenv("OLLAMA_MODEL", "llama3.1:8b")

    # Asynchronously sends a crafted prompt to the Ollama API.
    # Returns: The text string response generated by the LLM.
    async def generate_response(self, prompt: str, round_num: int = 1, history: Optional[List[Dict]] = None) -> str:
        # If running inside Docker (OLLAMA_BASE_URL is set), prioritize self.ollama_url
        if "ollama:" in self.ollama_url:
            candidate_urls = [self.ollama_url, "http://localhost:11434", "http://127.0.0.1:11434"]
        else:
            candidate_urls = ["http://localhost:11434", "http://127.0.0.1:11434", self.ollama_url]
        
        for base_url in candidate_urls:
            endpoint = f"{base_url}/api/generate"
            tags_endpoint = f"{base_url}/api/tags"

            try:
                # Fast check to query available models on Ollama instance
                async with httpx.AsyncClient(timeout=3.0) as client:
                    tags_res = await client.get(tags_endpoint)
                    if tags_res.status_code == 200:
                        models_data = tags_res.json().get("models", [])
                        model_names = [m.get("name", "") for m in models_data if m.get("name")]
                        
                        model_to_use = self.model
                        if model_names:
                            matched = [m for m in model_names if self.model in m]
                            model_to_use = matched[0] if matched else model_names[0]

                        print(f"[{self.country.upper()}] Calling Ollama model '{model_to_use}' on GPU via {base_url}...")

                        # Timeout and optimized options for fast inference on 4GB GPU
                        async with httpx.AsyncClient(timeout=180.0) as gen_client:
                            payload = {
                                "model": model_to_use,
                                "prompt": prompt,
                                "stream": False,
                                "keep_alive": "1h",
                                "options": {
                                    "temperature": 0.3,
                                    "num_predict": 75,
                                    "num_ctx": 1024
                                }
                            }
                            res = await gen_client.post(endpoint, json=payload)
                            if res.status_code == 200:
                                data = res.json()
                                response_text = data.get("response", "").strip()
                                if response_text:
                                    cleaned = self._clean_response(response_text)
                                    if cleaned and not self._is_repetitive_filler(cleaned):
                                        print(f"[{self.country.upper()}] Successfully received Ollama generation: {cleaned[:60]}...")
                                        return cleaned
            except Exception as e:
                print(f"[{self.country.upper()}] Error contacting {base_url}: {type(e).__name__} - {e}")
                logger.warning(f"Connection failed to {base_url}: {e}")

        print(f"[{self.country.upper()}] Ollama offline or timed out; using diplomatic fallback.")
        return self._generate_fallback_response(round_num=round_num, history=history)

    # Constructs the prompt combining persona, priorities, and negotiation history.
    # Returns: A new proposal generated by the LLM via generate_response.
    async def make_proposal(self, issue: str, history: List[Dict]) -> str:
        # Construct a prompt that injects self.country, self.positions['priorities']
        # Add the 'issue' context.
        # Append the 'history' so the agent knows what was previously discussed.
        # Instruct the model to respond concisely (e.g., 1-2 sentences).
        country_name = self.country.upper()
        priorities = self.positions.get("priorities", [])
        priorities_str = "; ".join(priorities) if priorities else "standard trade terms"
        round_num = len(history) + 1

        history_context = ""
        if history:
            history_lines = []
            for item in history:
                r_num = item.get("round", "")
                usa_p = item.get("usa_proposal", "")
                china_r = item.get("china_response", "")
                history_lines.append(f"Round {r_num}: USA: '{usa_p}' | China: '{china_r}'")
            history_context = "Previous History:\n" + "\n".join(history_lines) + "\n"

        prompt = (
            f"You are a diplomat representing {country_name} in Round {round_num} trade negotiations regarding '{issue}'.\n"
            f"Your country's core priorities are: {priorities_str}.\n"
            f"{history_context}"
            f"Formulate a negotiation proposal or response. "
            f"Respond with a single concise, professional sentence (1-2 sentences max) explicitly addressing your priorities ({priorities_str}). "
            f"Do not include intro text or markdown formatting."
        )

        return await self.generate_response(prompt, round_num=round_num, history=history)

    def _clean_response(self, text: str) -> str:
        """Strips unwanted preambles or quotes from LLM output."""
        cleaned = text.strip()
        if cleaned.startswith('"') and cleaned.endswith('"'):
            cleaned = cleaned[1:-1].strip()
        lines = [line.strip() for line in cleaned.splitlines() if line.strip()]
        if lines:
            for line in lines:
                if not line.lower().startswith("here is") and not line.lower().startswith("sure"):
                    return line
            return lines[0]
        return cleaned

    def _is_repetitive_filler(self, text: str) -> bool:
        """Detects if LLM output is repetitive generic filler without actual proposal terms."""
        lower = text.lower().strip()
        filler_patterns = [
            "i propose the following:",
            "in response to the round",
            "in response to round",
            "regarding 'intellectual proprietary",
            "i propose the following",
        ]
        if any(lower.endswith(p) for p in filler_patterns) or (lower.count("in response to") > 0 and len(lower) < 90):
            return True
        return False

    def _generate_fallback_response(self, round_num: int = 1, history: Optional[List[Dict]] = None) -> str:
        """Generates dynamic, high-quality evolving negotiation proposals across rounds if LLM is offline."""
        priorities = self.positions.get("priorities", [])
        p1 = priorities[0] if len(priorities) > 0 else "reduce technology product tariffs"
        p2 = priorities[1] if len(priorities) > 1 else "strengthen intellectual property protection"

        country_key = self.country.lower()

        if country_key == "usa":
            if round_num == 1:
                return f"The USA proposes an initial agreement to {p1.lower()} and {p2.lower()}."
            elif round_num == 2:
                return f"In response to China's terms, the USA offers a 20% tariff reduction on technology products in exchange for binding clauses on {p2.lower()}."
            elif round_num == 3:
                return f"The USA agrees to grant expanded market access for agricultural products, provided strict IP protection enforcement is guaranteed."
            elif round_num == 4:
                return f"The USA confirms readiness to finalize tariff schedule cuts subject to mutual bilateral compliance audits."
            else:
                return f"The USA accepts the consolidated compromise framework balancing tariff reductions with mutual intellectual property safeguards."

        elif country_key == "china":
            if round_num == 1:
                return f"China agrees to open dialogue provided we gain greater market access for agricultural products and limit restrictions on technology transfer."
            elif round_num == 2:
                return f"China welcomes USA's terms and proposes reciprocal flexibility to lower agricultural duties while easing technology transfer restrictions."
            elif round_num == 3:
                return f"China agrees to enhanced IP compliance mechanisms provided technology transfer limits are relaxed on key agricultural machinery."
            elif round_num == 4:
                return f"China commits to expanding agricultural import quotas by 25% in direct exchange for USA's tech tariff concessions."
            else:
                return f"China approves the final bilateral compromise agreement for market access and technology transfer terms."

        return f"{self.country.upper()} proposes progressive terms for round {round_num} regarding {p1.lower()}."
